#pragma once
#include <initializer_list>
#include <string>

/**
 * @brief Класс Очередь (Queue)
 * @details Реализует коллекцию целых чисел с операциями:
 * enqueue - добавление элемента в конец очереди,
 * dequeue - извлечение элемента из начала очереди,
 * peek - чтение головного элемента.
 */
class Queue
{
private:
    /**
     * @brief Узел односвязного списка
     * @details Хранит значение элемента и указатель на следующий узел
     */
    struct Node
    {
        int data;      ///< Значение элемента
        Node* next;    ///< Указатель на следующий узел

        /**
         * @brief Конструктор узла
         * @details Создает узел с заданным значением и нулевым указателем
         * @param value значение элемента
         */
        explicit Node(const int value) : data(value), next(nullptr) {}
    };

    /**
     * @brief Количество элементов в очереди
     * @details Хранит текущий размер очереди
     */
    size_t count;

public:
    /**
     * @brief Конструктор по умолчанию
     * @details Создает пустую очередь
     */
    Queue();

    /**
     * @brief Конструктор со списком инициализации
     * @details Создает очередь и наполняет ее элементами из списка
     * @param init список инициализации с целыми числами
     */
    explicit Queue(const std::initializer_list<int> init);

    /**
     * @brief Конструктор копирования
     * @details Создает копию другой очереди
     * @param other копируемая очередь
     */
    Queue(const Queue& other);

    /**
     * @brief Конструктор перемещения
     * @details Перемещает ресурсы из другой очереди
     * @param other перемещаемая очередь
     */
    Queue(Queue&& other) noexcept;

    /**
     * @brief Деструктор
     * @details Освобождает память, занятую элементами очереди
     */
    ~Queue();

    /**
     * @brief Оператор присваивания копированием
     * @details Копирует содержимое другой очереди в текущую
     * @param other копируемая очередь
     * @return ссылка на текущую очередь
     */
    Queue& operator=(const Queue& other);

    /**
     * @brief Оператор присваивания перемещением
     * @details Перемещает содержимое другой очереди в текущую
     * @param other перемещаемая очередь
     * @return ссылка на текущую очередь
     */
    Queue& operator=(Queue&& other) noexcept;

    /**
     * @brief Добавление элемента в конец очереди
     * @details Помещает значение в хвост очереди
     * @param value добавляемое значение
     */
    void enqueue(const int value);

    /**
     * @brief Извлечение элемента из начала очереди
     * @details Удаляет головной элемент и возвращает его значение
     * @return значение извлеченного элемента
     */
    int dequeue();

    /**
     * @brief Чтение головного элемента
     * @details Возвращает значение первого элемента без его удаления
     * @return значение головного элемента
     */
    int peek() const;

    /**
     * @brief Проверка очереди на пустоту
     * @details Определяет, содержит ли очередь хотя бы один элемент
     * @return true если очередь пуста, иначе false
     */
    bool isEmpty() const;

    /**
     * @brief Получить размер очереди
     * @details Возвращает текущее количество элементов
     * @return количество элементов в очереди
     */
    size_t size() const;

    /**
     * @brief Очистка очереди
     * @details Удаляет все элементы из очереди
     */
    void clear();

    /**
     * @brief Сериализация в строку
     * @details Формирует строковое представление всех элементов очереди
     * @return строка с элементами очереди
     */
    std::string toString() const;

    /**
     * @brief Оператор добавления элемента
     * @details Добавляет значение в конец очереди
     * @param value добавляемое значение
     * @return ссылка на текущую очередь
     */
    Queue& operator<<(const int value);

    /**
     * @brief Оператор извлечения элемента
     * @details Извлекает значение из начала очереди в переданную переменную
     * @param value переменная для сохранения извлеченного значения
     * @return ссылка на текущую очередь
     */
    Queue& operator>>(int value);

    /**
     * @brief Проверка наличия элемента
     * @details Определяет, содержится ли заданное значение в очереди
     * @param value искомое значение
     * @return true если элемент найден, иначе false
     */
    bool contains(const int value) const;
};
